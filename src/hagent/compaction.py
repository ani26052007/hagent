"""History compaction.

When the message list grows past a character budget, the middle of the history is replaced by
short notes. The system prompt, the task, and the most recent messages stay verbatim.

Shape is preserved so any chat API accepts it:  system, user(task + notes), assistant, user, ...
The notes live inside the task message (so there are never two consecutive user messages),
and the kept tail always starts with an assistant message.

The notes have two parts:
  1. A model-written summary. It is validated: weak models often copy the transcript back
     (agent labels, code blocks, hundreds of words) instead of summarizing. A summary that fails
     validation is replaced by a deterministic one built from the commands that were run.
  2. Optionally, the current repository state (the live `git diff`), generated by code. The diff
     is the ground truth for "what has been edited", so the agent never has to trust a summary
     for it. It is regenerated at every compaction and never fed back to the summarizer.
"""

from __future__ import annotations

import re
from typing import Callable

from .textutil import extract_bash_blocks, truncate_middle

SUMMARY_MARK = "\n\n## Summary of earlier work (auto-compacted; the full history was dropped)\n"
STATE_MARK = "\n\n## Repository state at the time of compaction (generated from `git diff`; run it again for the latest)\n"
STATE_NOTE = ("Code you read before this point is no longer visible. Before editing, re-read only "
              "the exact lines you will change.")

_PER_MESSAGE_CHARS = 1500
_TRANSCRIPT_CHARS = 40_000
MAX_SUMMARY_WORDS = 450       # the compactor is asked for <= 300; above this it is not summarizing
_PREVIOUS_NOTES_CHARS = 2500  # cap on earlier notes carried into the fallback summary
_STATE_DIFF_CHARS = 4000      # diff shown in the state section
_FALLBACK_COMMANDS = 30

_COPIED_MARKERS = ("[AGENT]", "[OUTPUT]", "<returncode>", "<output>")
_FENCE = re.compile(r"^\s*```.*$", re.MULTILINE)
_FILE_HEADER = re.compile(r"^diff --git a/(\S+) b/", re.MULTILINE)


def total_chars(messages: list[dict]) -> int:
    return sum(len(m["content"]) for m in messages)


def split_summary(task_message_content: str) -> tuple[str, str]:
    """Split the task message into (task text, notes or ''). The notes include the state section."""
    if SUMMARY_MARK in task_message_content:
        task, _, summary = task_message_content.partition(SUMMARY_MARK)
        return task, summary
    return task_message_content, ""


def strip_state(notes: str) -> str:
    """The notes without the generated repository-state section."""
    return notes.partition(STATE_MARK)[0]


def render_transcript(messages: list[dict]) -> str:
    parts = []
    for m in messages:
        label = "AGENT" if m["role"] == "assistant" else "OUTPUT"
        parts.append(f"[{label}]\n{truncate_middle(m['content'], _PER_MESSAGE_CHARS)}")
    return truncate_middle("\n\n".join(parts), _TRANSCRIPT_CHARS)


def summary_problem(text: str | None) -> str | None:
    """Why a model-written summary is unusable, or None if it is acceptable."""
    if not text or not text.strip():
        return "empty"
    if any(marker in text for marker in _COPIED_MARKERS):
        return "copied transcript labels"
    if len(_FENCE.findall(text)) > 2:
        return "copied code blocks"
    words = len(text.split())
    if words > MAX_SUMMARY_WORDS:
        return f"too long ({words} words)"
    return None


def clean_summary(text: str) -> str:
    """Drop the fence lines of the single small code block a valid summary may contain."""
    return _FENCE.sub("", text).strip()


def fallback_summary(middle: list[dict], previous: str) -> str:
    """Deterministic summary used when the model summary is missing or unusable:
    the earlier notes (capped) plus the commands that were run."""
    cmds = []
    for m in middle:
        if m["role"] == "assistant":
            blocks, _ = extract_bash_blocks(m["content"])
            if blocks:
                cmds.append(" ".join(blocks[0].split())[:100])
    lines = []
    previous = strip_state(previous).strip()
    if previous:
        lines.append(truncate_middle(previous, _PREVIOUS_NOTES_CHARS))
    lines.append("(Automatic summary unavailable. Commands run in the dropped part of the history:)")
    lines += [f"- {c}" for c in cmds[-_FALLBACK_COMMANDS:]]
    return "\n".join(lines)


def render_state(diff: str) -> str:
    """Body of the generated repository-state section."""
    files = _FILE_HEADER.findall(diff or "")
    if not files:
        return f"No files have been changed yet.\n{STATE_NOTE}"
    return (f"Files changed so far: {', '.join(files)}\n{STATE_NOTE}\n"
            f"Current diff:\n{truncate_middle(diff, _STATE_DIFF_CHARS)}")


def maybe_compact(
    messages: list[dict],
    summarize: Callable[[str, str], str | None],
    ctx_char_limit: int,
    keep_last: int,
    state: Callable[[], str] | None = None,
) -> bool:
    """Compact `messages` in place if over budget. Returns True if it compacted.

    `state`, if given, returns the current `git diff`; it is shown in its own section of the notes
    and is never passed back to the summarizer."""
    if ctx_char_limit <= 0 or total_chars(messages) <= ctx_char_limit:
        return False
    if len(messages) <= 2 + keep_last:
        return False

    start = len(messages) - keep_last
    while start < len(messages) and messages[start]["role"] != "assistant":
        start += 1  # the tail must begin with an assistant message
    if start >= len(messages) - 1:
        return False
    middle = messages[2:start]
    if not middle:
        return False

    task_text, previous = split_summary(messages[1]["content"])
    previous = strip_state(previous)
    summary = None
    try:
        summary = summarize(render_transcript(middle), previous)
    except Exception:  # a failing summarizer must never kill the run
        summary = None
    if summary_problem(summary):
        summary = fallback_summary(middle, previous)
    else:
        summary = clean_summary(summary)

    notes = summary.strip()
    if state is not None:
        try:
            notes += STATE_MARK + render_state(state())
        except Exception:  # the state section is a convenience; it must never kill the run
            pass

    new_task = {"role": "user", "content": task_text + SUMMARY_MARK + notes}
    messages[:] = [messages[0], new_task] + messages[start:]
    return True
